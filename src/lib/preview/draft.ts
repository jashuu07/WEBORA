import type { IndustryId, Page, Section, Website } from '@/types';
import {
  buildCopyDeck,
  makeContext,
  type CopyContext,
} from '@/services/ai/local-engine/copywriter';
import { existingIndustryImages } from '@/lib/media/stock-server';
import { getPack } from '@/lib/industry/packs';
import { getStyle } from '@/lib/design/styles';
import { DEFAULT_SPACING } from '@/lib/sections/schemas';

/**
 * Instant draft copy for the /create live preview.
 *
 * The full generation pipeline writes pages, sections, SEO and provenance —
 * work that only matters once the owner commits. While they are still typing,
 * they mostly want to see *their* words in *their* industry's layout. So this
 * module builds a screenful of real sections directly from the industry pack
 * and the design tokens: no network, no model, no database write.
 *
 * It is the same content library the generator uses, composed for one screen —
 * and the UI labels it as a live draft that is not saved anywhere.
 */

const PREVIEW_SECTIONS = ['hero', 'about', 'services', 'testimonials', 'cta'] as const;

export function buildLiveDraft({
  business,
  styleId,
  fallbackIndustry,
}: {
  business: { name: string; description: string; city?: string; services?: string[]; industry?: string };
  styleId: string;
  fallbackIndustry: IndustryId;
}): { website: Website; industry: IndustryId; packLabel: string } {
  const industry = (business.industry as IndustryId) || fallbackIndustry;
  const pack = getPack(industry);
  const style = getStyle(styleId);
  const ctx = makeContext(
    {
      name: business.name || 'Your business',
      type: '',
      industry,
      description: business.description,
      city: business.city ?? '',
      country: 'India',
      services: business.services ?? [],
      currency: 'INR',
      tone: pack.defaultTone,
      tags: [],
    },
    pack,
    1,
  );
  const deck = buildCopyDeck(ctx);
  const images = existingIndustryImages(industry);
  const stamp = new Date().toISOString();

  const website: Website = {
    id: 'live-draft',
    userId: 'draft',
    name: business.name || 'Your business',
    status: 'draft',
    slug: 'live-draft',
    industry,
    styleId: style.id,
    tokens: style.tokens,
    business: ctx.profile,
    settings: {
      primaryColor: style.tokens.accent,
      accentColor: style.tokens.accent,
      logoText: business.name || 'Your business',
      logoUrl: '',
      fontPair: style.tokens.headingFont,
      showWeboraBadge: true,
      whatsappFloat: true,
      contactFormEnabled: true,
      mapEmbedEnabled: true,
      bookingEnabled: false,
      social: {},
    },
    pages: [
      {
        id: 'draft-home',
        websiteId: 'live-draft',
        title: 'Home',
        slug: 'home',
        inNav: true,
        updatedAt: stamp,
        seo: {
          title: `${business.name || 'Your business'} · live draft`,
          description: business.description.slice(0, 155),
          keywords: [],
          slug: 'home',
        },
        sections: PREVIEW_SECTIONS.map((type) => draftSection(type, ctx, deck, images)),
      } satisfies Page,
    ],
    seo: {
      title: `${business.name || 'Your business'} · live draft`,
      description: business.description.slice(0, 155),
      keywords: [],
      slug: 'live-draft',
    },
    templateId: '',
    createdAt: stamp,
    updatedAt: stamp,
    // Labelled as a draft: nothing here has been generated by the full pipeline
    // or saved anywhere, and the UI says so next to the preview.
    generation: { engine: 'local', templateId: '', generatedAt: stamp, stages: [] },
  };

  return { website, industry, packLabel: pack.label };
}

/** Draft sections reuse the exact props shape the full generator produces. */
function draftSection(
  type: (typeof PREVIEW_SECTIONS)[number],
  ctx: CopyContext,
  deck: ReturnType<typeof buildCopyDeck>,
  images: string[],
): Section {
  const pack = getPack(ctx.profile.industry);
  const base = { id: `draft-${type}`, visible: true, label: type, spacing: { ...DEFAULT_SPACING } };

  if (type === 'hero') {
    return {
      ...base,
      type: 'hero',
      props: {
        eyebrow: deck.hero.eyebrow,
        heading: deck.hero.heading,
        sub: deck.hero.sub,
        primaryLabel: pack.primaryCta,
        primaryHref: '/contact',
        secondaryLabel: pack.secondaryCta,
        secondaryHref: '/services',
        image: images[0],
        layout: pack.defaultTone === 'bold' ? 'overlay' : 'split',
        trustLine: deck.hero.trustLine,
      },
    };
  }
  if (type === 'about') {
    return { ...base, type: 'about', props: { ...deck.about, image: images[1] ?? images[0], layout: 'image-left' } };
  }
  if (type === 'services') {
    return {
      ...base,
      type: 'services',
      props: {
        eyebrow: 'What we do',
        heading: pack.offersHeading,
        sub: pack.offersSub,
        columns: '3',
        showIcons: true,
        showPrices: true,
        items: deck.offers,
      },
    };
  }
  if (type === 'testimonials') {
    return {
      ...base,
      type: 'testimonials',
      props: {
        eyebrow: 'Reviews',
        heading: 'What customers say',
        items: deck.testimonials,
        layout: 'grid',
      },
    };
  }
  return {
    ...base,
    type: 'cta',
    props: {
      heading: pack.promise,
      sub: pack.heroSub,
      primaryLabel: pack.primaryCta,
      primaryHref: '/contact',
      tone: 'accent',
    },
  };
}
