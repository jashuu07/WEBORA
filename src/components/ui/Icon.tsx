export function Icon({
  name,
  className,
  strokeWidth = 1.7,
}: {
  name?: string;
  className?: string;
  strokeWidth?: number;
}) {
  const Component = REGISTRY[name ?? 'star'] ?? Sparkles;
  return <Component className={className} strokeWidth={strokeWidth} aria-hidden />;
}

export const ICON_NAMES = Object.keys(REGISTRY);
export function hasIcon(name: string) {
  return Boolean(REGISTRY[name]);
}
