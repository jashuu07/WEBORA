export async function generateMetadata({ params }: { params: Promise<{ doc: string }> }): Promise<Metadata> {
  const { doc } = await params;
  const entry = DOCS[doc];
  return { title: entry?.title ?? 'Legal' };
}

export function generateStaticParams() {
  return Object.keys(DOCS).map((doc) => ({ doc }));
}

export default async function LegalPage({ params }: { params: Promise<{ doc: string }> }) {
  const { doc } = await params;
  const entry = DOCS[doc];
  if (!entry) notFound();

  return (
    <article className="mx-auto w-full max-w-3xl px-5 py-16 sm:px-8">
      <p className="eyebrow mb-3">Legal</p>
      <h1 className="display-3">{entry.title}</h1>
      <p className="mt-3 text-[0.86rem] text-[var(--text-muted)]">Last updated {entry.updated}</p>

      <div className="mt-10 flex flex-col gap-8">
        {entry.sections.map((section) => (
          <section key={section.heading}>
            <h2 className="text-[1.1rem] font-semibold">{section.heading}</h2>
            <div className="mt-3 flex flex-col gap-3">
              {section.body.map((paragraph) => (
                <p key={paragraph} className="text-[0.94rem] leading-relaxed text-[var(--text-muted)]">
                  {paragraph}
                </p>
              ))}
            </div>
          </section>
        ))}
      </div>

      <div className="mt-12 border-t border-[var(--line)] pt-6 text-[0.86rem] text-[var(--text-muted)]">
        <p>
          Questions? See the other documents:{' '}
          {Object.entries(DOCS)
            .filter(([key]) => key !== doc)
            .map(([key, value], index) => (
              <span key={key}>
                {index > 0 ? ' · ' : ''}
                <Link href={`/legal/${key}`} className="font-medium text-[var(--accent)] hover:underline">
                  {value.title}
                </Link>
              </span>
            ))}
        </p>
      </div>
    </article>
  );
}
